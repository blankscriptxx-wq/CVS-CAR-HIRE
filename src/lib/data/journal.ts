export function getJournalPost(slug: string): JournalPost | undefined {
  return journalPosts.find((p) => p.slug === slug);
}

/**
 * A post is live once its publishedAt date has arrived. Future-dated posts are
 * written and committed ahead of time and reveal themselves automatically on
 * their day (pages use ISR revalidation), so the Journal "auto-publishes" on a
 * schedule with no daily automation and full editorial control.
 */
export function isPublished(post: JournalPost, now: number = Date.now()): boolean {
  const t = Date.parse(post.publishedAt);
  return Number.isNaN(t) ? true : t <= now;
}

/** Published posts only, newest first. */
export function getPublishedPosts(now: number = Date.now()): JournalPost[] {
  return journalPosts
    .filter((p) => isPublished(p, now))
    .sort((a, b) => Date.parse(b.publishedAt) - Date.parse(a.publishedAt));
}
